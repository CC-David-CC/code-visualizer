def build_authority_handler_registry() -> StaticContributionRegistry[Handler]:
    registry: StaticContributionRegistry[Handler] = StaticContributionRegistry()
    contributions: tuple[tuple[str, Handler], ...] = (
        *program_handlers(),
        *domain_handlers(),
        *language_handlers(),
        ("project.rename", _rename_project),
        ("diagram.create", _create_diagram),
        ("diagram.delete", _delete_diagram),
        ("diagram.restore", _restore_diagram),
        ("diagram.rename", _rename_diagram),
        ("diagram.move", _move_diagram),
        ("diagram.duplicate", _duplicate_diagram),
        ("diagram.replace_snapshot", _replace_diagram_snapshot),
        ("function.replace_spec", _replace_function_spec),
        ("program.function.replace_signature", _replace_function_signature),
        ("python.configure_runtime", _configure_python_runtime),
        ("drakon.insert", _insert_drakon),
        ("drakon.remove", _remove_drakon),
        ("drakon.restore", _restore_drakon),
        ("drakon.insert_block", _insert_drakon_block),
        ("drakon.remove_block", _remove_drakon_block),
        ("drakon.replace", _replace_drakon_atom),
        ("drakon.wrap", _wrap_drakon_block),
        ("drakon.unwrap", _unwrap_drakon_atom),
        ("drakon.set_text", _set_drakon_text),
        ("drakon.move_block", _move_drakon_block),
        ("mindmap.add_topic", _add_mind_map_topic),
        ("mindmap.update_topic", _update_mind_map_topic),
        ("mindmap.move_topic", _move_mind_map_topic),
        ("mindmap.remove_topic", _remove_mind_map_topic),
        ("mindmap.add_cross_link", _add_mind_map_cross_link),
        ("mindmap.set_layout", _set_mind_map_layout),
        ("view.set_anchor", _set_view_anchor),
        ("semantic.concept.put", _put_semantic_concept),
        ("semantic.concept.delete", _delete_semantic_concept),
        ("semantic.relation.put", _put_authored_relation),
        ("semantic.relation.delete", _delete_authored_relation),
        ("projection.put", _put_projection_definition),
        ("projection.delete", _delete_projection_definition),
        ("projection.materialize", _materialize_projection),
        ("freeform.create", _create_freeform_shape),
        ("freeform.transform", _transform_freeform_object),
        ("freeform.remove", _remove_freeform_objects),
        ("freeform.connect", _create_freeform_connector),
        ("freeform.set_properties", _set_freeform_properties),
        ("freeform.arrange", _arrange_freeform_objects),
        ("freeform.layer.add", _add_freeform_layer),
        ("freeform.layer.update", _update_freeform_layer),
        ("freeform.layer.remove", _remove_freeform_layer),
        ("freeform.guide.add", _add_freeform_guide),
        ("freeform.guide.remove", _remove_freeform_guide),
        ("freeform.canvas.configure", _configure_freeform_canvas),
        ("asset.register", _register_managed_asset),
        ("asset.remove", _remove_managed_asset),
        ("shape_pack.register", _register_shape_pack),
        ("shape_pack.remove", _remove_shape_pack),
    )
    for order, (command_type, handler) in enumerate(contributions):
        registry.register(command_type, handler, order=order)
    return registry


def authority_handlers() -> dict[str, Handler]:
    return build_authority_handler_registry().mapping()
